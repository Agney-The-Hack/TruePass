const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("==================================================");
  console.log("  TruePass Web3 Smart Contract Deployment");
  console.log("==================================================");

  const [deployer] = await hre.ethers.getSigners();
  const network = await hre.ethers.provider.getNetwork();

  console.log(`Deploying with account: ${deployer.address}`);
  console.log(`Target Network Chain ID: ${network.chainId}`);

  const TruePassTicket = await hre.ethers.getContractFactory("TruePassTicket");
  const truePass = await TruePassTicket.deploy();
  await truePass.waitForDeployment();

  const contractAddress = await truePass.getAddress();
  console.log(`✅ TruePassTicket deployed successfully to: ${contractAddress}`);

  // Fetch ABI from artifacts
  const artifact = await hre.artifacts.readArtifact("TruePassTicket");

  // Format contract info file for frontend
  const contractInfoContent = `/**
 * Automatically generated by scripts/deploy.js
 * DO NOT EDIT MANUALLY.
 */
window.TRUEPASS_CONFIG = {
  chainId: ${network.chainId.toString()},
  contractAddress: "${contractAddress}",
  deployerAddress: "${deployer.address}",
  deployedAt: "${new Date().toISOString()}",
  abi: ${JSON.stringify(artifact.abi, null, 2)}
};
`;

  const outputPath = path.join(__dirname, "..", "contractInfo.js");
  fs.writeFileSync(outputPath, contractInfoContent, "utf8");
  console.log(`✅ Frontend configuration exported to: ${outputPath}`);

  console.log("\nDeployment summary:");
  console.log(`- Contract: TruePassTicket`);
  console.log(`- Address:  ${contractAddress}`);
  console.log(`- Network:  ${network.name || "chainId " + network.chainId}`);
  console.log("==================================================\n");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("Deployment failed:", error);
    process.exit(1);
  });
